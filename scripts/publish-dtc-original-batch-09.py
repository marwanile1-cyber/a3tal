def text(item):
    return html.escape(str(item), quote=True)


def para(value):
    return "<p>" + text(value) + "</p>"


def list_html(items):
    return "<ul>" + "".join("<li>" + text(value) + "</li>" for value in items) + "</ul>"


def render(article):
    code = article["code"]
    lines = [
        para(article["summary"]),
        "<h2>ما معنى كود " + code + " وكيف يعمل النظام؟</h2>",
        para(article["how"]),
        "<h2>أعراض ظهور كود " + code + "</h2>",
        list_html(article["symptoms"]),
        "<h2>الأسباب المحتملة من دون تغيير قطع عشوائي</h2>",
        list_html(article["causes"]),
        "<h2>تشخيص كود " + code + " خطوة بخطوة</h2>",
    ]
    for i, (heading, body) in enumerate(article["steps"], start=1):
        lines.extend(["<h3>" + str(i) + ". " + text(heading) + "</h3>", para(body)])
    lines.extend([
        "<h2>كيف تفرق بين هذا الكود والأكواد المشابهة؟</h2>",
        para(article["difference"]),
        "<h2>الإصلاح المناسب ومتى تستبدل القطعة؟</h2>",
        para(article["repair"]),
        "<h2>هل يمكن الاستمرار في القيادة؟</h2>",
        para(article["safety"]),
        "<h2>الأسئلة الشائعة عن " + code + "</h2>",
    ])
    for question, answer in article["faqs"]:
        lines.extend(["<h3>" + text(question) + "</h3>", para(answer)])
    related = article.get("related_codes", [])
    if related:
        # Direct, previously-published canonical DTC links; pending entries are not advertised.
        links = []
        for related_code in related:
            if related_code in FIXED_EXISTING and related_code not in {"P0190","P0205","P0481"}:
                links.append('<a href="https://a3tal.com/dtc/' + text(related_code.lower()) + '/">' + text(related_code) + '</a>')
        if links:
            lines.append("<h2>أدلة مرتبطة داخل مكتبة الأعطال</h2><p>" + ", ".join(links) + "</p>")
    lines.append("<p><strong>ملاحظة من فريق أعطال.كوم:</strong> الكود يحدد اختبارًا فشل في كمبيوتر السيارة، وليس حكمًا بأن قطعة معينة تالفة. ترتبط الخطوات بموديل السيارة ونوع المحرك ونشرة الصيانة الصحيحة.</p>")
    return "\n".join(lines)


def validate(items):
    codes = [row["code"] for row in items]
    if len(items) != 5 or len(set(codes)) != 5:
        raise RuntimeError("Unexpected batch count or duplicated codes")
    for row in items:
        code = row["code"]
        if not CODE_RE.fullmatch(code) or code in FIXED_EXISTING:
            raise RuntimeError("Code invalid or already covered by existing editorial pages: " + code)
        if row.get("scope") != "generic" or len(row.get("steps", [])) != 5 or len(row.get("faqs", [])) != 3:
            raise RuntimeError("Incomplete guide: " + code)
        if len(row.get("symptoms", [])) < 3 or len(row.get("causes", [])) < 3:
            raise RuntimeError("Incomplete symptoms/causes: " + code)
        if not row["source"].startswith(ALLOWED_SOURCES):
            raise RuntimeError("Unreviewed primary reference URL: " + code)
        body = render(row)
        if len(re.findall(r"\S+", re.sub(r"<[^>]*>", " ", body))) < 350:
            raise RuntimeError("Guide is too thin to publish: " + code)
    print("Validated", len(items), "unique original Arabic diagnostic guides", flush=True)


def request_admin(payload, write=False):
    global last_call
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    headers = {"X-A3tal-Key": KEY, "Authorization": "Bearer " + KEY,
               "Content-Type": "application/json", "Accept": "application/json",
               "User-Agent": "A3tal-Original-DTC-Editorial/1.0", "Cache-Control": "no-store"}
    attempts = 1 if write else 4
    for attempt in range(attempts):
        time.sleep(max(0, 22 - (time.monotonic() - last_call)))
        last_call = time.monotonic()
        req = urllib.request.Request(API, data=body, headers=headers, method="POST")
        try:
            with urllib.request.urlopen(req, timeout=65) as response:
                obj = json.load(response)
            if obj.get("ok") is not True or "result" not in obj:
                raise RuntimeError("Unexpected Bridge result envelope")
            return obj["result"]
        except urllib.error.HTTPError as err:
            if not write and err.code in (429, 502, 503, 504, 520, 522, 524) and attempt < attempts - 1:
                print("Bridge read interrupted (HTTP", err.code, "), cooldown", flush=True)
                time.sleep(75 * (attempt + 1))
                continue
            raise RuntimeError("Bridge request error HTTP " + str(err.code) + "; op=" + payload.get("op", "")) from None
        except (TimeoutError, urllib.error.URLError):
            if not write and attempt < attempts - 1:
                time.sleep(45 * (attempt + 1))
                continue
            raise RuntimeError("Bridge transport interruption; op=" + payload.get("op", "")) from None


def get_public(code):
    # Always consult the code's actual public permalink before creating. A
    # browser-side denial should stop this operation, not falsely imply 404.
    url = BASE + "/dtc/" + code.lower() + "/?a3tal_publish_preflight=1"
    headers = {
        "User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 Chrome/129.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "ar,en;q=0.7",
    }
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=30) as res:
                content = res.read().decode("utf-8")
                return (res.geturl(), content)
        except urllib.error.HTTPError as err:
            if err.code == 404:
                return None
            if err.code not in (429, 502, 503, 504, 520, 522, 524) or attempt == 3:
                raise RuntimeError("Public preflight HTTP " + str(err.code) + " for " + code) from None
        except (urllib.error.URLError, TimeoutError):
            if attempt == 3:
                raise RuntimeError("Public preflight transport error for " + code) from None
        time.sleep(35 * (attempt + 1))
    raise RuntimeError("Public preflight never responded for " + code)


def publish_one(row):
    code = row["code"]
    # A legacy long-form guide may already cover this code without using a
    # /dtc/<code>/ permalink. The live catalog is our authoritative index.
    query_url = BASE + "/dtc/?code=" + urllib.parse.quote(code)
    headers = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 Chrome/129.0 Safari/537.36",
               "Accept": "text/html,application/xhtml+xml;q=0.9,*/*;q=0.8"}
    listing = None
    # Catalog lookup is a safe read. Transient Cloudflare errors can be retried;
    # never repeat publishing mutations after a lost response.
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(query_url, headers=headers), timeout=35) as res:
                listing = res.read().decode("utf-8")
            break
        except urllib.error.HTTPError as err:
            if err.code not in (429, 502, 503, 504, 520, 522, 524) or attempt == 3:
                raise RuntimeError("Catalog duplicate preflight failed HTTP " + str(err.code) + " for " + code) from None
            print("Transient catalog read HTTP", err.code, code, "attempt", attempt+1, flush=True)
        except (urllib.error.URLError, TimeoutError) as err:
            if attempt == 3:
                raise RuntimeError("Catalog duplicate preflight transport failed for " + code) from None
        time.sleep(35 * (attempt + 1))
    if listing is None:
        raise RuntimeError("Catalog duplicate preflight unavailable for " + code)
    if re.search(r"[1-9][0-9]*\s+شرحًا متاحًا", listing):
        print("Already covered by live DTC catalog:", code, "(will not duplicate)", flush=True)
        return "existing"
    if not re.search(r"0\s+شرحًا متاحًا", listing):
        raise RuntimeError("Catalog result count could not be verified for " + code)
    existing = get_public(code)
    if existing:
        if "d-detail-hero" in existing[1] and code in existing[1]:
            print("Already published: " + code + " (preserving existing article)", flush=True)
            return "existing"
        raise RuntimeError("URL already exists but is not verified DTC article: " + code)
    data = {
        "op": "platform_entity_upsert",
        "type": "a3_dtc",
        "slug": code.lower(),
        "title": "كود " + code + ": " + row["name"] + " | معنى العطل وطريقة التشخيص",
        "status": "publish",
        "excerpt": row["summary"][:245],
        "content": render(row),
        "meta": {
            "_a3_dtc_code": code,
            "_a3_dtc_system": row["system"],
            "_a3_code_scope": row["scope"],
            "_a3_drive_advice": row["safety"],
            "_a3_source_url": row["source"],
            "_a3_source_checked_at": "2026-10-13",
            "_a3_dtc_batch": "A3TAL-DTC-2026-10-13-09-5",
        }
    }
    # Publishing is a non-idempotent side effect. On ambiguous 522, stop after
    # read-only verification. Never replay the write in this run.
    print("Publishing", code, flush=True)
    expected_path = "/dtc/" + code.lower() + "/"
    try:
        result = request_admin(data, write=True)
    except RuntimeError as err:
        if "HTTP 522" not in str(err) and "Bridge transport interruption" not in str(err):
            raise
        print("Write response unknown:", code, "performing read-only reconciliation", flush=True)
        for check_attempt in range(3):
            time.sleep(40 * (check_attempt + 1))
            live = get_public(code)
            if live and "d-detail-hero" in live[1] and code in live[1]:
                print("PUBLISHED after ambiguous bridge response:", code, live[0], flush=True)
                return "created"
            if live:
                raise RuntimeError("Unexpected page at slug after ambiguous write: " + code)
        raise RuntimeError("UNCONFIRMED write for " + code + ". Stop safely and inspect before retrying.") from err
    if result.get("slug") != code.lower() or expected_path not in result.get("link", ""):
        raise RuntimeError("WordPress returned unexpected post link for " + code)
    if not isinstance(result.get("id"), int) or result["id"] <= 0:
        raise RuntimeError("WordPress did not return a valid post id")
    print("PUBLISHED:", code, result["link"], "post", result["id"], flush=True)
    return "created"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--from-index", type=int, default=0)
    args = parser.parse_args()
    rows = json.loads(BATCH.read_text(encoding="utf-8"))["items"]
    validate(rows)
    if args.dry_run:
        for row in rows:
            print(row["code"], row["name"], "words=", len(re.findall(r"\S+", re.sub(r"<[^>]*>", " ", render(row)))), flush=True)
        return
    if not KEY:
        raise RuntimeError("Missing A3tal Direct Bridge key")
    info = request_admin({"op": "site_info"})
    if info.get("active_theme") != "a3tal-global":
        raise RuntimeError("Unexpected active WordPress theme")
    created, existing = 0, 0
    for row in rows[max(0, args.from_index):]:
        outcome = publish_one(row)
        created += outcome == "created"
        existing += outcome == "existing"
        time.sleep(12)
    print("FINISHED: created", created, "already published", existing, flush=True)


if __name__ == "__main__":
    main()
